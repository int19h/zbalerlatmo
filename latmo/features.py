"""Generate the Latin-input GSUB lookups as OpenType feature-file source.

The generated lookups turn Latin-orthography Lojban into the same sequence of
Zbalermorna glyphs that the upstream fonts use for their Private Use Area
encoding, with glides and diphthongs already formed. The font's own upstream
lookups (attitudinal shorthand, contextual forms, self-dotting and so on, which
differ from font to font) run afterwards and finish the job.

Every Latin character is mapped by cmap to an *input* glyph named ``lat.*``.
Input glyphs never survive shaping: the last generated lookup lowers each of
them to an upstream glyph. Between the two, a few internal variants are used:

- ``lat.X.nm``: X inside a cmevla (name); its vowels render as full vowels.
- ``lat.i.gl``, ``lat.u.gl``: i/u before a vowel, rendered as glide radicals.
- ``lat.V.str``: a stressed vowel as typed (capital or accented); it is
  decomposed into ``lat.V`` + ``lat.stress`` first.

The order of the lookups is load-bearing; see ``LOOKUP_ORDER`` below.
"""

from __future__ import annotations

CONSONANTS = "bcdfgjklmnprstvxz"
VOWELS = "aeiouy"
# The four true diphthongs; written as two vowels in Latin.
DIPHTHONGS = ["ai", "ei", "oi", "au"]

# Upstream glyph names.
RADICAL = {c: c + "y" for c in CONSONANTS}
RADICAL["b"] = "by"
VOWEL_MARK = {v: v + "bu" for v in VOWELS}
VOWEL_FULL = {v: "seplime" + v + "bu" for v in VOWELS}
DIPHTHONG_MARK = {d: d + "bu" for d in DIPHTHONGS}
DIPHTHONG_FULL = {d: "seplime" + d + "bu" for d in DIPHTHONGS}
GLIDE = {"i": "iy", "u": "uy"}
PERIOD = "denpabu"
APOSTROPHE = "yhy"
SEPARATOR = "slakabu"  # the comma inside a word
STRESS = "bahebu"
STRETCH = "tcenabu"

# Glyphs that are Lojban letters for the purpose of context matching.
LETTER_KEYS = list(CONSONANTS) + list(VOWELS) + ["apos", "sep", "stress", "tilde"]


def lat(key: str) -> str:
    return "lat." + key


def nm(key: str) -> str:
    return "lat." + key + ".nm"


def internal_glyphs() -> list[str]:
    """Glyphs that only exist between generated lookups."""
    names = [lat("apos"), lat("sep")]
    names += [nm(k) for k in LETTER_KEYS]
    names += [lat("i.gl"), lat("u.gl")]
    for a, b in stress_pairs():
        names += [lat(a + "_stress_" + b), nm(a + "_stress_" + b)]
    return names


def glide_pairs() -> list[tuple[str, str]]:
    return [(g, v) for g in "iu" for v in VOWELS]


def diphthong_pairs() -> list[tuple[str, str]]:
    return [(d[0], d[1]) for d in DIPHTHONGS]


def stress_pairs() -> list[tuple[str, str]]:
    """Two-vowel syllables whose stress, written on the first vowel, is moved
    after the second: a glide with its vowel, and the diphthongs."""
    return glide_pairs() + diphthong_pairs()


def stress_lookups(name: str, pairs: list[tuple[str, str]]) -> list[str]:
    """A ligature lookup that catches V1 stress V2 [stress], and one that
    splits it into V1 V2 stress."""
    out = [f"lookup {name}Liga {{"]
    for a, b in pairs:
        for f in (lat, nm):
            out.append(f"    sub {f(a)} {f('stress')} {f(b)} {f('stress')} by {f(a + '_stress_' + b)};")
            out.append(f"    sub {f(a)} {f('stress')} {f(b)} by {f(a + '_stress_' + b)};")
    out.append(f"}} {name}Liga;")
    out.append(f"lookup {name}Split {{")
    for a, b in pairs:
        for f in (lat, nm):
            out.append(f"    sub {f(a + '_stress_' + b)} by {f(a)} {f(b)} {f('stress')};")
    out.append(f"}} {name}Split;\n")
    return out


def cls(names) -> str:
    return "[" + " ".join(names) + "]"


def generate() -> str:
    """Return feature-file source defining the generated lookups.

    The lookups are standalone (not registered in any feature); the build
    step merges them, in order, ahead of the font's own lookups in ``rlig``.
    """
    plain_letters = [lat(k) for k in LETTER_KEYS]
    named_letters = [nm(k) for k in LETTER_KEYS]
    vowels = [lat(v) for v in VOWELS]
    vowels_nm = [nm(v) for v in VOWELS]
    letters = [lat(k) for k in CONSONANTS + VOWELS]
    # What may stand immediately left of an apostrophe or word-internal comma.
    left_ctx = vowels + [lat("stress"), lat("tilde")]
    letter_left_ctx = letters + [lat("stress"), lat("tilde")]

    out: list[str] = []
    w = out.append

    w("# Generated by latmo/features.py; do not edit.\n")
    w(f"@latVowel = {cls(vowels)};")
    w(f"@latVowelNm = {cls(vowels_nm)};")
    w(f"@latLetter = {cls(letters)};")
    w(f"@latLeftV = {cls(left_ctx)};")
    w(f"@latLeftL = {cls(letter_left_ctx)};")
    w(f"@latCons = {cls(lat(c) for c in CONSONANTS)};")
    w(f"@latConsNm = {cls(nm(c) for c in CONSONANTS)};")
    w(f"@latPlain = {cls(plain_letters)};")
    w(f"@latNamed = {cls(named_letters)};")
    w("")

    # 1. Stressed vowels as typed (capital, acute, grave) -> vowel + stress.
    w("lookup latDecompose {")
    for v in VOWELS:
        w(f"    sub {lat(v)}.str by {lat(v)} {lat('stress')};")
    w("} latDecompose;\n")

    # 2. Apostrophe, h and comma. An apostrophe in Lojban always stands
    #    between vowels; anywhere else ' and ’ are quotation marks. A comma
    #    between letters separates syllables; anywhere else it is punctuation.
    w("lookup latToApos {")
    w(f"    sub {cls([lat('quotesingle'), lat('quoteright'), lat('h')])} by {lat('apos')};")
    w("} latToApos;")
    w("lookup latToSep {")
    w(f"    sub {lat('comma')} by {lat('sep')};")
    w("} latToSep;")
    w("lookup latPunct {")
    w(f"    sub @latLeftV {cls([lat('quotesingle'), lat('quoteright')])}' lookup latToApos @latVowel;")
    w(f"    sub {lat('h')}' lookup latToApos;")
    w(f"    sub @latLeftL {lat('comma')}' lookup latToSep @latLetter;")
    w("} latPunct;\n")

    # 3. Names. A cmevla is the only kind of word that ends in a consonant.
    #    Mark a consonant that no Lojban letter follows (normally the period
    #    after the name; also a space, punctuation or the end of the text,
    #    so a forgotten trailing period does no harm), then propagate the
    #    mark leftwards letter by letter. Reverse chaining lookups run right
    #    to left, so each substitution is visible as lookahead to the glyph
    #    on its left. The first matching rule wins; the middle rule leaves a
    #    word-internal consonant unchanged.
    w("lookup latNames {")
    w(f"    rsub @latPlain' @latNamed by @latNamed;")
    w(f"    rsub @latCons' @latPlain by @latCons;")
    w(f"    rsub @latCons' by @latConsNm;")
    w("} latNames;\n")

    # 4. Stress written on the first vowel of a two-vowel syllable moves
    #    after the second vowel, so the glide and diphthong rules still see
    #    two adjacent vowels. A syllable is stressed once: stress on both
    #    halves (all-caps .UI, COI) is one stress mark, as two would read as
    #    a double-dot dynamic. Glide syllables (.Ua, .UI) are handled before
    #    the glide rule and diphthongs (lAi) after it, so that in .mAias. the
    #    i still goes to the glide (ma-ias), not to a diphthong.
    out.extend(stress_lookups("latGlideStress", glide_pairs()))

    # 5. Glides: i or u before a vowel. This must precede diphthong
    #    formation: .maias. is ma-ias, not mai-as. Of two i/u before a
    #    vowel only the second is a glide: .mariias. is ma-ri-ias.
    w("lookup latToGlide {")
    w(f"    sub {cls([lat('i'), lat('u'), nm('i'), nm('u')])} by "
      f"{cls([lat('i.gl'), lat('u.gl'), lat('i.gl'), lat('u.gl')])};")
    w("} latToGlide;")
    iu, iu_nm = cls([lat("i"), lat("u")]), cls([nm("i"), nm("u")])
    w("lookup latGlides {")
    w(f"    ignore sub {iu}' {iu} @latVowel;")
    w(f"    ignore sub {iu_nm}' {iu_nm} @latVowelNm;")
    w(f"    sub {iu}' lookup latToGlide @latVowel;")
    w(f"    sub {iu_nm}' lookup latToGlide @latVowelNm;")
    w("} latGlides;\n")

    out.extend(stress_lookups("latDiphStress", diphthong_pairs()))

    # 6. Diphthongs, here rather than left to the upstream lookups: not every
    #    upstream font forms them from separate vowels (Fira Code ZLM expects
    #    the IME to send them composed).
    w("lookup latDiphthongs {")
    for d in DIPHTHONGS:
        w(f"    sub {lat(d[0])} {lat(d[1])} by {DIPHTHONG_MARK[d]};")
        w(f"    sub {nm(d[0])} {nm(d[1])} by {DIPHTHONG_FULL[d]};")
    w("} latDiphthongs;\n")

    # 7. Lower every remaining input glyph to its upstream glyph.
    lower: list[tuple[str, str]] = []
    for c in CONSONANTS:
        lower += [(lat(c), RADICAL[c]), (nm(c), RADICAL[c])]
    for v in VOWELS:
        lower += [(lat(v), VOWEL_MARK[v]), (nm(v), VOWEL_FULL[v])]
    lower += [
        (lat("i.gl"), GLIDE["i"]), (lat("u.gl"), GLIDE["u"]),
        (lat("period"), PERIOD),
        (lat("apos"), APOSTROPHE), (nm("apos"), APOSTROPHE),
        (lat("sep"), SEPARATOR), (nm("sep"), SEPARATOR),
        (lat("stress"), STRESS), (nm("stress"), STRESS),
        (lat("tilde"), STRETCH), (nm("tilde"), STRETCH),
        (lat("comma"), "comma"),
        (lat("quotesingle"), "quotesingle"),
        (lat("quoteright"), "quoteright"),
    ]
    w("lookup latLower {")
    for src, dst in lower:
        w(f"    sub {src} by {dst};")
    w("} latLower;\n")

    return "\n".join(out) + "\n"


# Lookups that must be registered (in this order) ahead of the upstream
# lookups. Helper lookups that are only called from contextual lookups are
# not listed here.
LOOKUP_ORDER = [
    "latDecompose",
    "latPunct",
    "latNames",
    "latGlideStressLiga",
    "latGlideStressSplit",
    "latGlides",
    "latDiphStressLiga",
    "latDiphStressSplit",
    "latDiphthongs",
    "latLower",
]
